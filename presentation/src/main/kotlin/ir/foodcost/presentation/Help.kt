    private val BY_ID: Map<String, Term> = TERMS.associateBy { it.id }

    fun term(id: String): Term? = BY_ID[id]

    /** The terms whose name, other names or meaning match [query], however its spaces and letters were typed. */
    fun search(query: String): List<Term> {
        if (query.isBlank()) return TERMS
        val byName = TERMS.filter { t -> Persian.matches(t.title, query) || t.aka.any { Persian.matches(it, query) } }
        val byMeaning = TERMS.filter { it !in byName && Persian.matches(it.meaning, query) }
        return byName + byMeaning
    }
