    /** The koobideh of the examples, ready in the calculator: prices per kilo, grams per portion, a 630,000 toman menu price. */
    fun sample(money: MoneyFormat): QuickInput {
        var input = QuickInput(dishName = "چلوکباب کوبیده (نمونه)", menuPrice = money.editable(6_300_000))
        listOf(
            Triple("گوشت", 14_500_000L, "170"),
            Triple("دمبه", 11_000_000L, "30"),
            Triple("پیاز", 800_000L, "50"),
            Triple("برنج", 3_500_000L, "200"),
        ).forEach { (name, rials, grams) ->
            input = input.withRow(input.rows.lastIndex, QuickRow(name, money.editable(rials), grams))
        }
        return input
    }
